#!/usr/bin/env node
import crypto from 'node:crypto';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { spawnSync } from 'node:child_process';

const root = process.cwd();
const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'ev4-project-pack-test-'));
const failures = [];

function fail(message) {
  failures.push(message);
}

function copy(source, destination) {
  fs.mkdirSync(path.dirname(destination), { recursive: true });
  fs.cpSync(source, destination, { recursive: true });
}

function run(args, expectedExit = 0) {
  const result = spawnSync(process.execPath, ['scripts/build-project-pack.mjs', ...args], {
    cwd: temp,
    encoding: 'utf8',
    maxBuffer: 16 * 1024 * 1024,
    shell: false
  });
  if (result.status !== expectedExit) {
    fail(`build ${args.join(' ')} expected exit ${expectedExit}, received ${result.status}. ${result.stderr || result.stdout}`);
  }
  return result;
}

function treeDigest(directory) {
  const hash = crypto.createHash('sha256');
  function visit(current, prefix = '') {
    for (const name of fs.readdirSync(current).sort()) {
      const absolute = path.join(current, name);
      const relative = prefix ? `${prefix}/${name}` : name;
      if (fs.statSync(absolute).isDirectory()) visit(absolute, relative);
      else {
        hash.update(relative);
        hash.update('\0');
        hash.update(fs.readFileSync(absolute));
        hash.update('\0');
      }
    }
  }
  visit(directory);
  return hash.digest('hex');
}

try {
  copy(path.join(root, 'scripts', 'build-project-pack.mjs'), path.join(temp, 'scripts', 'build-project-pack.mjs'));
  copy(path.join(root, 'runtime', 'project-pack-source-map.v1.json'), path.join(temp, 'runtime', 'project-pack-source-map.v1.json'));
  copy(path.join(root, 'runtime', 'project-pack'), path.join(temp, 'runtime', 'project-pack'));
  copy(path.join(root, 'dist', 'chatgpt-project'), path.join(temp, 'dist', 'chatgpt-project'));

  run(['--verify']);
  const first = treeDigest(path.join(temp, 'dist', 'chatgpt-project'));
  run(['--verify']);
  const second = treeDigest(path.join(temp, 'dist', 'chatgpt-project'));
  if (first !== second) fail('Two builds from identical sources are not byte-identical.');

  const handEdited = path.join(temp, 'dist', 'chatgpt-project', 'knowledge', '01_RUNTIME_CORE.md');
  fs.appendFileSync(handEdited, '\nhand edit\n');
  run(['--verify'], 1);

  run(['--write']);
  run(['--verify']);
  const restored = treeDigest(path.join(temp, 'dist', 'chatgpt-project'));
  if (restored !== first) fail('Atomic regeneration did not restore canonical generated bytes.');

  const canonicalSource = path.join(temp, 'runtime', 'project-pack', '01_RUNTIME_CORE.md');
  fs.appendFileSync(canonicalSource, '\nCanonical source mutation.\n');
  run(['--write']);
  run(['--verify']);
  const changed = treeDigest(path.join(temp, 'dist', 'chatgpt-project'));
  if (changed === first) fail('Canonical source mutation did not change generated output.');

  const report = JSON.parse(fs.readFileSync(path.join(temp, 'dist', 'chatgpt-project', 'BUILD_REPORT.json'), 'utf8'));
  const manifest = JSON.parse(fs.readFileSync(path.join(temp, 'dist', 'chatgpt-project', 'SOURCE_PACK_MANIFEST.json'), 'utf8'));
  if (report.manifest_file_count !== manifest.files.length) fail('Manifest and Build Report file counts disagree.');
  if (report.generated_file_count !== manifest.files.length + 2) fail('Generated file count does not include Manifest and Build Report exactly once.');
} finally {
  fs.rmSync(temp, { recursive: true, force: true });
}

if (failures.length > 0) {
  console.error('Project Pack determinism tests failed:');
  for (const failure of failures) console.error(`- ${failure}`);
  process.exit(1);
}

console.log('Project Pack deterministic build, source mutation, hand-edit rejection, and count tests passed.');
